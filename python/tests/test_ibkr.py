"""The IBKR port reproduces what the TypeScript computes, for every recorded case.

`testdata/vendors/ibkr-fields.json` is generated by `make cases` from the real
`typescript/src/vendors/ibkr/fields.ts`, over figures measured against the live gateway on 2026-11-08.
Two implementations, one recorded truth, compared exactly — the same arrangement
`tests/test_cases.py` gives the domain.

The arguments in that corpus are the TypeScript's shapes, so the reader below translates them: a
`Greeks` object arrives as a JSON object with camelCase keys, and a tick table as a dict with
string keys. That translation is the only liberty taken, and it is checked by the cases failing
loudly if it is wrong.
"""

import json
from pathlib import Path
from typing import Any

import pytest
from test_cases import decode  # the corpus's own $set/$date decoder, not a second copy

from optionality import ibkr

CASES = Path(__file__).resolve().parents[2] / "testdata" / "vendors" / "ibkr-fields.json"

#: toRecord -> to_record, greekFields -> greek_fields: snake_case is the only translation in this
#: package, and the corpus names the TypeScript's functions.
PORTED = {
    "grade": "grade",
    "greekFields": "greek_fields",
    "withMid": "with_mid",
    "hasFigures": "has_figures",
}


def corpus() -> dict[str, Any]:
    return json.loads(CASES.read_text())


def recorded() -> list[dict[str, Any]]:
    cases = corpus()["cases"]
    # there IS something to compare: an empty corpus would pass every assertion over it
    assert len(cases) >= 16, f"only {len(cases)} cases in {CASES}"
    return cases


def _call(fn: str, args: list[Any]) -> Any:
    name = PORTED.get(fn)
    assert name, f"the corpus holds {fn}, which this port does not implement"
    func = getattr(ibkr, name)
    if fn == "greekFields":
        row = args[0]
        return func(
            ibkr.Greeks(
                implied_vol=row["impliedVol"],
                delta=row["delta"],
                gamma=row["gamma"],
                vega=row["vega"],
                theta=row["theta"],
            )
        )
    return func(*args)


def _plain(value: Any) -> Any:
    """A Grade is a NamedTuple here and an object there, so compare as the corpus wrote it."""
    return dict(value._asdict()) if hasattr(value, "_asdict") else value


@pytest.mark.parametrize("case", recorded(), ids=lambda c: f"{c['fn']}: {c['name']}")
def test_reproduces_the_typescript(case: dict[str, Any]) -> None:
    assert _plain(_call(case["fn"], case["args"])) == case["expect"]


def test_the_corpus_covers_every_function_this_module_ports() -> None:
    """Both directions, because either gap is a silent one.

    A function here that the corpus does not name is unheld; a function the corpus names that is
    missing here is a port with a hole. `cases/vendors.test.ts` holds the TypeScript's exports to
    the corpus, and this holds the corpus to the port.
    """
    cased = {c["fn"] for c in recorded()}
    assert cased == set(PORTED), f"corpus and port disagree: {cased ^ set(PORTED)}"
    for ts, py in PORTED.items():
        assert callable(getattr(ibkr, py, None)), f"{ts} maps to {py}, which does not exist"


#: The corpus writes the TypeScript's shapes, and three of them differ here: a JS `Record` with
#: number keys arrives with string ones, a JS `Set` arrives as the generator's `{"$set": [...]}`,
#: and a frozenset is not a set literal. A constant with no entry is compared AS IT STANDS — which
#: is what a number needs — so a constant added to `ibkr/fields.ts` is held here the moment
#: `make cases` records it, rather than when somebody remembers to add a line.
SHAPES: dict[str, Any] = {
    "PRICE_TICKS": lambda recorded: {int(k): v for k, v in recorded.items()},
    "GREEK_TICKS": lambda recorded: decode(recorded),
}
MINE: dict[str, Any] = {"GREEK_TICKS": set}


@pytest.mark.parametrize("name", sorted(corpus()["constants"]))
def test_the_constants_match_the_corpus(name: str) -> None:
    """Every constant the corpus states, which the case list cannot see.

    `PRICE_TICKS` is the whole translation for prices: a delayed id mapped to the wrong field would
    show a bid as a last, plausibly and wrongly. `MARKET_DATA_DELAYED_FROZEN` is the grade this
    client ASKS the gateway for, and it is here because nothing else could hold it: the fake
    gateway answers `reqMarketDataType` with nothing, as the real one does, so no replay can see
    which grade was asked and the two clients could ask for different data in silence.
    """
    recorded = SHAPES.get(name, lambda v: v)(corpus()["constants"][name])
    mine = getattr(ibkr, name, None)
    assert mine is not None, f"the corpus states {name}, which this port does not define"
    assert MINE.get(name, lambda v: v)(mine) == recorded


def test_the_delayed_ids_land_where_the_live_ones_do() -> None:
    """Which is the point of the price table, and the one thing comparing it cannot say."""
    for live, delayed in ((1, 66), (2, 67), (4, 68), (9, 75)):
        assert ibkr.PRICE_TICKS[delayed] == ibkr.PRICE_TICKS[live]


def test_the_greek_ticks_are_the_model_computation_by_ib_asyncs_own_map() -> None:
    """The ids `ib_async` itself files as the MODEL's greeks, live and delayed. 53 was here until
    #257's review: it is the custom computation, and the client now waits for the model's, so a
    delayed option would have waited out the timeout for a tick that never comes."""
    wrapper = pytest.importorskip("ib_async.wrapper")
    model = {tick for tick, name in wrapper.GREEKS_TICK_MAP.items() if name == "modelGreeks"}
    assert set(ibkr.GREEK_TICKS) == model == {13, 83}


def test_a_bool_is_not_a_price() -> None:
    """`typeof x === "number"` is false for a boolean; `isinstance(x, int)` is TRUE for one.

    Unported, a `bid_price` of True averages into a mid of 0.5 or 1.0. The corpus cannot catch it:
    the TypeScript's own `Quote` type never puts a boolean in a price field.
    """
    assert "mid_price" not in ibkr.with_mid({"bid_price": True, "ask_price": True})


def test_a_grade_is_two_facts_and_not_a_scale() -> None:
    """Grade 4 is both, and the gateway drew that distinction per contract in one response."""
    assert ibkr.grade(4) != ibkr.grade(3)
    assert ibkr.grade(4) != ibkr.grade(2)
    assert ibkr.grade(0) is None and ibkr.grade(7) is None
