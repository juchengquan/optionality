"""The Yahoo port reproduces what the TypeScript computes, for every recorded case.

`testdata/vendors/yahoo-fields.json` is generated by `make cases` from the real
`backend/src/vendors/yahoo/fields.ts`, over rows recorded from Yahoo on 2026-11-08. So this is not
"the Python looks right to me" — it is the same inputs through two implementations, compared
exactly, which is what `tests/test_cases.py` does for the domain and what makes this half of the
package a PORT rather than a second opinion.

The fetch itself is injected, never real: `yfinance` would reach the network, and a suite that did
that would be slow, flaky and dependent on a market being open.
"""

import json
from pathlib import Path
from typing import Any

import pytest

from optionality import yahoo

CASES = Path(__file__).resolve().parents[2] / "testdata" / "vendors" / "yahoo-fields.json"


def recorded() -> list[dict[str, Any]]:
    corpus = json.loads(CASES.read_text())
    cases = corpus["cases"]
    # there IS something to compare: an empty corpus would pass every assertion parametrised over it
    assert len(cases) >= 8, f"only {len(cases)} cases in {CASES}"
    return cases


@pytest.mark.parametrize("case", recorded(), ids=lambda c: c["name"])
def test_reproduces_the_typescript(case: dict[str, Any]) -> None:
    assert case["fn"] == "toRecord", f"unported function in the corpus: {case['fn']}"
    code, row = case["args"]
    assert yahoo.to_record(code, row) == case["expect"]


def test_the_corpus_covers_every_function_this_module_ports() -> None:
    """The coverage guard's other half, on this side.

    `cases/vendors.test.ts` holds the TypeScript's exports to the corpus. This holds the corpus to
    what the PORT claims to implement — otherwise a function could be added here, mirror nothing,
    and be the only thing in the cased half that nothing compares.
    """
    ported = {name for name in ("to_record",) if callable(getattr(yahoo, name, None))}
    cased = {c["fn"] for c in recorded()}
    # toRecord -> to_record is the only translation, as everywhere else in this package
    assert {n.replace("_", "") for n in ported} <= {n.lower() for n in cased}


def test_one_bounded_call_for_the_whole_list(monkeypatch: pytest.MonkeyPatch) -> None:
    """The invariant's sense of bounded: ONE call for every code, not one per code."""
    asked: list[list[str]] = []

    def rows(codes: list[str]) -> dict[str, dict[str, Any]]:
        asked.append(codes)
        return {c: {"regularMarketPrice": 1.0} for c in codes}

    monkeypatch.setattr(yahoo, "_fetch_rows", rows)
    batch = yahoo.quotes(["^GSPC", "^VIX", "^SKEW"])
    assert asked == [["^GSPC", "^VIX", "^SKEW"]]
    assert [r["code"] for r in batch.records] == ["^GSPC", "^VIX", "^SKEW"]
    assert batch.unknown == []


def test_a_code_yahoo_does_not_carry_is_unknown(monkeypatch: pytest.MonkeyPatch) -> None:
    """Unknown, not missing. The sweep quarantines an unknown contract and counts a silent one, so
    which of the two this is decides whether a rule gets disabled (ADR 0015)."""
    monkeypatch.setattr(
        yahoo, "_fetch_rows",
        lambda codes: {"^GSPC": {"regularMarketPrice": 7376.86}, "^NOPE": {"shortName": "nothing"}})
    batch = yahoo.quotes(["^GSPC", "^NOPE", "^ABSENT"])
    assert [r["code"] for r in batch.records] == ["^GSPC"]
    # one answered with no price at all, one was not answered for
    assert batch.unknown == ["^NOPE", "^ABSENT"]


def test_an_empty_list_asks_nothing(monkeypatch: pytest.MonkeyPatch) -> None:
    def boom(codes: list[str]) -> dict[str, dict[str, Any]]:
        raise AssertionError("asked Yahoo for nothing at all")

    monkeypatch.setattr(yahoo, "_fetch_rows", boom)
    assert yahoo.quotes([]) == ([], [])


def test_a_bool_is_not_a_duration() -> None:
    """`typeof x === "number"` is false for a boolean; `isinstance(x, int)` is TRUE for one.

    Unported, that difference writes `delayed_by_minutes: True` — a duration of "yes". The corpus
    cannot catch it, because the TypeScript's own type never produces a boolean there.
    """
    got = yahoo.to_record("^X", {"exchangeDataDelayedBy": True})
    assert "delayed" not in got
    assert "delayed_by_minutes" not in got
