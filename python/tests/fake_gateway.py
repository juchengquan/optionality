"""A stub IB Gateway that replays one recorded conversation to `ib_async` (ADR 0021, Decision 7).

The Python twin of `typescript/src/vendors/ibkr/fake.ts`, and it follows the same five rules,
which `testdata/vendors/ibkr-gateway/README.md` writes down for "a stub in any language". It says
nothing of its own: every byte it sends is in a recording, captured from the real gateway or
constructed and labelled so, and the same files are what the TypeScript's stub replays to its own
client. One truth, two clients, and nothing in either stub the other does not also send.

So a run against it proves the CLIENT and is never evidence about IB Gateway, an account's
entitlements, a dead session or an open market.

What it adds to the TypeScript's: `received`, every message the client sent after its version
range. `ib_async` is a general-purpose client that asks for positions, orders and the account when
it connects through `IB.connectAsync`, and the TypeScript sends none of that; recording what
arrives is how a test holds the Python to the same five messages rather than trusting it to.

Not a test module, so pytest collects nothing here.
"""

import asyncio
import json
import struct
from pathlib import Path
from typing import Any

#: the recordings, shared ground both languages read (`tools/check-boundaries.mjs`)
RECORDINGS = Path(__file__).resolve().parents[2] / "testdata" / "vendors" / "ibkr-gateway"
#: what each recording's client returned, generated by the TypeScript's `ibkr/replay.ts`
EXPECTED = RECORDINGS / "expected"

#: stands for the id of the request a reply answers, wherever it appears — inside text too: error
#: 300 reads "Can't find EId with tickerId:$reqId"
REQ_ID = "$reqId"

#: the contract fields a request is matched on: the ones that change the answer
CONTRACT_KEYS = ("symbol", "secType", "lastTradeDateOrContractMonth", "strike", "right", "exchange", "tradingClass")

#: where reqContractDetails (version 8) and reqMktData (version 11) both carry those fields at
#: protocol 157, after the message id, version and request id — the README's rule 3, and the same
#: positions for both clients, because `ib_async` writes a Contract in the order the TypeScript does
AT = {
    "symbol": 4,
    "secType": 5,
    "lastTradeDateOrContractMonth": 6,
    "strike": 7,
    "right": 8,
    "exchange": 10,
    "tradingClass": 14,
}

#: the message ids the stub reads; everything else a client sends is accepted and never answered
START_API, REQ_MKT_DATA, CANCEL_MKT_DATA, REQ_CONTRACT_DATA = "71", "1", "2", "9"

#: what the client sends before its first frame, raw
PREFIX = b"API\0"

type Message = list[str]


def conversation_names() -> list[str]:
    """Every recording, by name, sorted."""
    return sorted(p.stem for p in RECORDINGS.glob("*.json"))


def expectation_names() -> list[str]:
    return sorted(p.stem for p in EXPECTED.glob("*.json"))


def load_conversation(name: str) -> dict[str, Any]:
    """A recording as written. Its SHAPE is the TypeScript's `parseConversation`'s to refuse, and
    `recordings.test.ts` runs it over every file; this reads only what a replay needs."""
    conversation: dict[str, Any] = json.loads((RECORDINGS / f"{name}.json").read_text())
    assert conversation["conversation"] == name, f"{name}.json calls itself {conversation['conversation']}"
    return conversation


def load_expectation(name: str) -> dict[str, Any]:
    expectation: dict[str, Any] = json.loads((EXPECTED / f"{name}.json").read_text())
    return expectation


def fill(message: Message, req_id: str) -> Message:
    """The request's own id, wherever the recording left a place for it."""
    return [field.replace(REQ_ID, req_id) for field in message]


def frame(fields: Message) -> bytes:
    """One message for the wire: each field NUL-terminated, the whole prefixed by its length in
    bytes, big-endian. ASCII and strictly so — the TypeScript's encoder refuses anything else, so a
    recording that carried it could not be replayed there either."""
    payload = "".join(f"{field}\0" for field in fields).encode("ascii")
    return struct.pack(">I", len(payload)) + payload


def read_frames(buffer: bytes) -> tuple[list[Message], bytes]:
    """Whole frames out of a byte stream, with whatever is left over for next time."""
    messages: list[Message] = []
    at = 0
    while len(buffer) - at >= 4:
        (size,) = struct.unpack_from(">I", buffer, at)
        if len(buffer) - at - 4 < size:
            break
        fields = buffer[at + 4 : at + 4 + size].decode("ascii").split("\0")
        fields.pop()  # the trailing NUL is punctuation, not an empty last field
        messages.append(fields)
        at += 4 + size
    return messages, buffer[at:]


def names(exchange: dict[str, Any], fields: Message) -> bool:
    """Whether a request names this exchange's contract: the strike by value, because "8100.0" and
    "8100" are one double to the gateway, and the rest as exact text."""
    for key in CONTRACT_KEYS:
        sent = fields[AT[key]] if AT[key] < len(fields) else ""
        recorded = exchange["contract"][key]
        if key == "strike":
            if _number(sent) != _number(recorded):
                return False
        elif sent != recorded:
            return False
    return True


def _number(text: str) -> float:
    """JavaScript's `Number` for the strings a strike can be: empty is 0, as it is there."""
    return float(text) if text.strip() else 0.0


class FakeGateway:
    """Listening on loopback, on a port the OS picks, replaying `conversation`.

    `server_version` claims a protocol other than the recording's, so a client's refusal of an old
    gateway can be tested — a number rather than a reply, as in the TypeScript's stub.
    """

    def __init__(self, conversation: dict[str, Any], server_version: str | None = None) -> None:
        self.conversation = conversation
        self.server_version = server_version
        self.port = 0
        #: contract lookups asked, over the stub's life — so a test can see the conid cache save one
        self.lookups = 0
        #: every message a client sent after its version range, in order, over the stub's life
        self.received: list[Message] = []
        #: how many requests each request-and-contract has had, keyed by the first exchange naming it
        self._turns: dict[int, int] = {}
        self._open: set[asyncio.StreamWriter] = set()
        self._server: asyncio.Server | None = None

    async def start(self) -> "FakeGateway":
        self._server = await asyncio.start_server(self._serve, "127.0.0.1", 0)
        self.port = self._server.sockets[0].getsockname()[1]
        return self

    @property
    def connections(self) -> int:
        """Clients connected right now, so a test can see one let go."""
        return len(self._open)

    async def close(self) -> None:
        """Aborted, not just closed: a client still holding its end would otherwise keep
        `wait_closed` waiting — the TypeScript's stub hung on exactly that, as a hook timeout."""
        for writer in list(self._open):
            writer.transport.abort()
        if self._server is not None:
            self._server.close()
            await self._server.wait_closed()

    async def _serve(self, reader: asyncio.StreamReader, writer: asyncio.StreamWriter) -> None:
        self._open.add(writer)
        buffer = b""
        greeted = False
        #: market-data requests answered on THIS connection, by id, for what a cancel is told
        answered: dict[str, dict[str, Any]] = {}

        def send(messages: list[Message], req_id: str | None = None) -> None:
            for message in messages:
                writer.write(frame(message if req_id is None else fill(message, req_id)))

        try:
            while chunk := await reader.read(65536):
                buffer += chunk
                if not greeted and buffer.startswith(PREFIX):
                    buffer = buffer[len(PREFIX) :]
                messages, buffer = read_frames(buffer)
                for fields in messages:
                    if not greeted:
                        # rule 1: the version range, answered with the recording's greeting
                        greeted = True
                        version, *clock = self.conversation["handshake"]["greeting"]
                        send([[self.server_version or version, *clock]])
                        continue
                    self.received.append(fields)
                    self._answer(fields, answered, send)
                await writer.drain()
        except (ConnectionError, asyncio.IncompleteReadError):
            pass  # a client closing its end is not a fault
        finally:
            self._open.discard(writer)
            writer.close()

    def _answer(self, fields: Message, answered: dict[str, dict[str, Any]], send: Any) -> None:
        message_id = fields[0] if fields else ""
        req_id = fields[2] if len(fields) > 2 else ""
        if message_id == START_API:
            # rule 2: the session's messages, in the order the gateway sent them
            send(self.conversation["handshake"]["onStartApi"])
            return
        if message_id in (REQ_CONTRACT_DATA, REQ_MKT_DATA):
            # rule 3: the exchange that names this contract, its id filled in
            request = "reqContractDetails" if message_id == REQ_CONTRACT_DATA else "reqMktData"
            if request == "reqContractDetails":
                self.lookups += 1
            recorded = [
                (i, e)
                for i, e in enumerate(self.conversation["exchanges"])
                if e["request"] == request and names(e, fields)
            ]
            if not recorded:
                return  # rule 4: nobody recorded an answer to this, so it gets none, ever
            first = recorded[0][0]
            turn = self._turns.get(first, 0)
            self._turns[first] = turn + 1
            _, exchange = recorded[min(turn, len(recorded) - 1)]
            if request == "reqMktData":
                answered[req_id] = exchange
            send(exchange["replies"], req_id)
            return
        if message_id == CANCEL_MKT_DATA:
            # rule 5: what the gateway said to that cancel, if anything
            exchange = answered.pop(req_id, None)
            send(exchange.get("onCancel", []) if exchange else [], req_id)
        # reqMarketDataType, and anything else, gets no answer, as from the real gateway


async def start_fake_gateway(name: str, server_version: str | None = None) -> FakeGateway:
    return await FakeGateway(load_conversation(name), server_version).start()
