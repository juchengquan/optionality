"""Same recording in, same quote batch out (ADR 0021, Decision 7).

Every conversation under `testdata/vendors/ibkr-gateway/` is replayed by `fake_gateway.py` to this
package's client, on `ib_async`, and what comes back — the batch, or the exact words it raised —
must be what the TypeScript's client made of the same bytes: `expected/<name>.json`, generated by
`typescript/src/vendors/ibkr/replay.ts`. Compared exactly, as the golden cases are, with
`test_cases.same`: `True` is not `1`, and a float is compared to the last bit.

## Replayed together, as the TypeScript replays them

The silent conversations each wait out the client's bounded wait, a second apiece under the
config every expectation records, so they are replayed side by side in one loop — `replay.ts`'s
`Promise.all` — and the cost is the slowest one rather than the sum. The waits are the client's
own completion rule (`quiet_ms`, `request_timeout_ms`, `connect_timeout_ms`), which is what is being
compared; nothing here sleeps for its own sake. Each replay is bounded on top, so a client that
hangs fails its own conversation instead of the suite.

## Coverage

Parametrized from the DIRECTORY, so a recording added tomorrow is replayed tomorrow — and fails
until the TypeScript has generated its expectation and this client reproduces it. The recordings
and the expectations are also held to each other by name, both ways, and to a floor, because a
parametrization over an empty directory passes by collecting nothing.
"""

import asyncio
from typing import Any

import pytest
from fake_gateway import conversation_names, expectation_names, load_conversation, load_expectation, start_fake_gateway
from test_cases import same

from optionality.ibkr import IbkrClient

#: the conversations there were when this was written; more is fine, fewer is a directory gone
FLOOR = 12
#: a replay that takes longer than this has hung, whatever its waits are configured to
HUNG = 15.0


async def outcome(client: IbkrClient, codes: list[str], port: int) -> dict[str, Any]:
    """What the client made of one ask, in the expectation's own terms: the batch under the
    service's field names, or `{"$throws": message}` with the stub's port spelled `<port>`."""
    try:
        batch = await client.fetch_quotes(codes)
    except Exception as err:  # noqa: BLE001 — every failure IS the outcome being compared
        return {"$throws": str(err).replace(f"127.0.0.1:{port}", "127.0.0.1:<port>")}
    return {"records": batch.records, "unknown": batch.unknown}


async def replay(name: str) -> dict[str, Any]:
    """One conversation, asked as `replay.ts` asks it: `ask`, then each of `later` in turn on the
    SAME client, so the connection and the conid cache carry over."""
    conversation = load_conversation(name)
    config = load_expectation(name)["config"]
    gateway = await start_fake_gateway(name)
    client = IbkrClient(
        port=gateway.port,
        client_id=config["clientId"],
        connect_timeout_ms=config["connectTimeoutMs"],
        request_timeout_ms=config["requestTimeoutMs"],
        quiet_ms=config["quietMs"],
    )
    try:
        result: dict[str, Any] = {"ask": conversation["ask"]}
        result["expect"] = await outcome(client, conversation["ask"], gateway.port)
        if "later" in conversation:
            result["later"] = [
                {"ask": codes, "expect": await outcome(client, codes, gateway.port)} for codes in conversation["later"]
            ]
        result["sent"] = sorted({fields[0] for fields in gateway.received})
        return result
    finally:
        client.close()
        await gateway.close()


async def replay_all(names: list[str]) -> dict[str, dict[str, Any]]:
    done = await asyncio.gather(*(asyncio.wait_for(replay(n), HUNG) for n in names), return_exceptions=True)
    return {
        name: {"crashed": repr(result)} if isinstance(result, BaseException) else result
        for name, result in zip(names, done, strict=True)
    }


@pytest.fixture(scope="module")
def replayed() -> dict[str, dict[str, Any]]:
    return asyncio.run(replay_all(conversation_names()))


@pytest.mark.parametrize("name", conversation_names())
def test_the_python_client_answers_what_the_typescript_did(name: str, replayed: dict[str, dict[str, Any]]) -> None:
    got = replayed[name]
    assert "crashed" not in got, f"{name}: the replay itself failed: {got['crashed']}"
    expected = load_expectation(name)
    assert got["ask"] == expected["ask"], f"{name}: the expectation was made for another ask"
    assert same(got["expect"], expected["expect"]), (
        f"{name}: the Python client said\n  {got['expect']!r}\nwhere the TypeScript's said\n  {expected['expect']!r}"
    )
    assert ("later" in got) == ("later" in expected), f"{name}: later asks on one side only"
    for i, (mine, theirs) in enumerate(zip(got.get("later", []), expected.get("later", []), strict=True)):
        assert mine["ask"] == theirs["ask"], f"{name}: later[{i}] was a different ask"
        assert same(mine["expect"], theirs["expect"]), (
            f"{name}: later[{i}]: the Python client said\n  {mine['expect']!r}\n"
            f"where the TypeScript's said\n  {theirs['expect']!r}"
        )


@pytest.mark.parametrize("name", conversation_names())
def test_the_python_client_sends_only_what_the_typescript_does(name: str, replayed: dict[str, dict[str, Any]]) -> None:
    """The TypeScript's five messages and startApi, and nothing account-shaped.

    `ib_async`'s `IB.connectAsync` asks for positions on every connect whatever its fetch flags
    say, and orders unless `readonly=True`. ADR 0019's point is that a quote fetch has nothing
    account-shaped in it, so this client connects through `ib_async`'s `Client` instead and sends
    what `messages.ts` sends: startApi (71), reqMarketDataType (59), reqContractDetails (9),
    reqMktData (1) and cancelMktData (2)."""
    got = replayed[name]
    assert "crashed" not in got, got.get("crashed")
    assert set(got["sent"]) <= {"71", "59", "9", "1", "2"}, f"{name}: the client also sent {got['sent']}"


def test_every_recording_has_its_expectation_and_its_python_result() -> None:
    recordings, expectations = set(conversation_names()), set(expectation_names())
    assert len(recordings) >= FLOOR, f"only {len(recordings)} recordings — the directory is not where it was"
    assert recordings - expectations == set(), (
        f"recorded but never expected: {sorted(recordings - expectations)} — run `make cases`"
    )
    assert expectations - recordings == set(), f"expected but never recorded: {sorted(expectations - recordings)}"
    # and the comparison is parametrized over exactly these — read off the test itself, so a list
    # written out by hand in its place, which would go stale, fails here
    (mark,) = test_the_python_client_answers_what_the_typescript_did.pytestmark  # type: ignore[attr-defined]
    assert set(mark.args[1]) == recordings, "the comparison does not replay every recording"
