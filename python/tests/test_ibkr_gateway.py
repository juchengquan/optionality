"""Same recording in, same quote batch out (ADR 0021, Decision 7).

Every conversation under `testdata/vendors/ibkr-gateway/` is replayed by `fake_gateway.py` to this
package's client, on `ib_async`, and what comes back — the batch, or the exact words it raised —
must be what the TypeScript's client made of the same bytes: `expected/<name>.json`, generated by
`typescript/src/vendors/ibkr/replay.ts`. Compared exactly, as the golden cases are, with
`test_cases.same`: `True` is not `1`, and a float is compared to the last bit.

## Replayed together, as the TypeScript replays them

The silent conversations each wait out the client's bounded wait, a second apiece under the
config every expectation records, so they are replayed side by side in one loop — `replay.ts`'s
`Promise.all` — and the cost is the slowest one rather than the sum. The waits are the client's
own completion rule (`quiet_ms`, `request_timeout_ms`, `connect_timeout_ms`), which is what is being
compared; nothing here sleeps for its own sake. Each replay is bounded on top, so a client that
hangs fails its own conversation instead of the suite.

## Coverage

Parametrized from the DIRECTORY, so a recording added tomorrow is replayed tomorrow — and fails
until the TypeScript has generated its expectation and this client reproduces it. The recordings
and the expectations are also held to each other by name, both ways, and to a floor, because a
parametrization over an empty directory passes by collecting nothing.

## A watch, step by step (ADR 0031)

As `replay.ts` replays one: start it, take its picture, and at each step tell the stub to send that
step's replies and wait until the client has READ them — the client's clock is a counter read once
per P&L message, and every step ends with the account's P&L, so the step has been read when the
clock has been read once for every P&L the stub wrote. A condition, not a timer. A watch's `before`
steps go while its start is still waiting, the last carrying the download end, so the start resolving
is that step's sign.
"""

import asyncio
import time
from typing import Any

import pytest
from fake_gateway import conversation_names, expectation_names, load_conversation, load_expectation, start_fake_gateway
from test_cases import same

from optionality.ibkr import IbkrAccountRefused, IbkrAccountWatch, IbkrClient

#: the conversations there were when this was written; more is fine, fewer is a directory gone
FLOOR = 23
#: the messages a watch sends: reqAccountUpdates, reqPnL, cancelPnL, reqPnLSingle, cancelPnLSingle
WATCH_MESSAGES = {"6", "92", "93", "94", "95"}
#: a replay that takes longer than this has hung, whatever its waits are configured to
HUNG = 15.0


async def outcome(client: IbkrClient, codes: list[str], port: int) -> dict[str, Any]:
    """What the client made of one ask, in the expectation's own terms: the batch under the
    service's field names, or `{"$throws": message}` with the stub's port spelled `<port>`."""
    try:
        batch = await client.fetch_quotes(codes)
    except Exception as err:  # noqa: BLE001 — every failure IS the outcome being compared
        return {"$throws": str(err).replace(f"127.0.0.1:{port}", "127.0.0.1:<port>")}
    return {"records": batch.records, "unknown": batch.unknown}


def subscriptions(gateway: Any) -> list[list[str]]:
    """The account subscriptions the stub was sent, whole, in order (ADR 0030)."""
    return [fields for fields in gateway.received if fields[0] == "6"]


async def unsubscribed(gateway: Any) -> None:
    """Until every subscribe has had its unsubscribe, or a second has passed: the unsubscribe goes
    as a read settles, and reaches the stub a moment after — `replay.ts`' `unsubscribed`."""
    until = time.monotonic() + 1
    while sum(1 if f[2] == "1" else -1 for f in subscriptions(gateway)) > 0 and time.monotonic() < until:
        await asyncio.sleep(0.005)


async def account_read(client: IbkrClient, gateway: Any, wanted: str | None) -> dict[str, Any]:
    """An account read in the expectation's terms: the answer, `{"$refused": message}` where the
    client refused to choose, or `{"$throws": message}` — and the subscriptions it sent."""
    before = len(subscriptions(gateway))
    got: Any
    try:
        got = await client.account(wanted)
    except IbkrAccountRefused as err:
        got = {"$refused": str(err)}
    except Exception as err:  # noqa: BLE001 — every failure IS the outcome being compared
        got = {"$throws": str(err)}
    await unsubscribed(gateway)
    return {"wanted": wanted, "expect": got, "sent": subscriptions(gateway)[before:]}


async def until(done: Any) -> None:
    """Until `done()`, or a second has passed — `replay.ts`' `until`."""
    limit = time.monotonic() + 1
    while not done() and time.monotonic() < limit:
        await asyncio.sleep(0.005)


async def watched(
    client: IbkrClient,
    gateway: Any,
    clock: list[int],
    wanted: str | None,
    ahead: int,
    steps: int,
    first: int,
    end: str,
) -> dict[str, Any]:
    """One watch in the expectation's terms, replayed as `replay.ts`' `watched` replays it."""
    before = len(gateway.received)

    def sent() -> list[list[str]]:
        return [f for f in gateway.received[before:] if f[0] in WATCH_MESSAGES]

    starting = asyncio.ensure_future(client.watch_account(wanted))
    for n in range(first, first + ahead):
        await gateway.step(n)
        # every step but the one the download ends at ends with a P&L; that one, with the start
        if n < first + ahead - 1:
            await until(lambda: clock[0] >= sum(1 for m in gateway.written if m[0] == "94"))
    first += ahead
    watch: IbkrAccountWatch
    try:
        watch = await starting
    except IbkrAccountRefused as err:
        await unsubscribed(gateway)
        return {"wanted": wanted, "start": {"$refused": str(err)}, "sent": sent()}
    except Exception as err:  # noqa: BLE001 — every failure IS the outcome being compared
        await unsubscribed(gateway)
        return {"wanted": wanted, "start": {"$throws": str(err)}, "sent": sent()}
    start = watch.picture()
    pictures = []
    for n in range(first, first + steps):
        await gateway.step(n)
        await until(lambda: clock[0] >= sum(1 for m in gateway.written if m[0] == "94"))
        pictures.append(watch.picture())
    if end == "drop":
        gateway.drop_connections()
        await until(lambda: watch.lost is not None)
    await watch.stop()
    await unsubscribed(gateway)
    lost = watch.lost
    return {
        "wanted": wanted,
        "start": start,
        "steps": pictures,
        "end": end,
        "lost": None if lost is None else str(lost),
        "last": watch.picture(),
        "sent": sent(),
    }


async def replay(name: str) -> dict[str, Any]:
    """One conversation, asked as `replay.ts` asks it: `ask`, then each of `later` in turn on the
    SAME client, so the connection and the conid cache carry over."""
    conversation = load_conversation(name)
    config = load_expectation(name)["config"]
    gateway = await start_fake_gateway(name)
    # the client's clock counts its readings, once per P&L message a watch reads
    clock = [0]

    def now() -> int:
        clock[0] += 1
        return clock[0]

    client = IbkrClient(
        port=gateway.port,
        client_id=config["clientId"],
        connect_timeout_ms=config["connectTimeoutMs"],
        request_timeout_ms=config["requestTimeoutMs"],
        quiet_ms=config["quietMs"],
        now=now,
    )
    try:
        result: dict[str, Any] = {"ask": conversation["ask"]}
        result["expect"] = await outcome(client, conversation["ask"], gateway.port)
        if "later" in conversation:
            result["later"] = [
                {"ask": codes, "expect": await outcome(client, codes, gateway.port)} for codes in conversation["later"]
            ]
        if "accountReads" in conversation:
            result["accountReads"] = [
                await account_read(client, gateway, read["wanted"]) for read in conversation["accountReads"]
            ]
        if "watches" in conversation:
            result["watches"] = []
            first = 1
            for spec in conversation["watches"]:
                ahead = spec.get("before", 0)
                result["watches"].append(
                    await watched(client, gateway, clock, spec["wanted"], ahead, spec["steps"], first, spec["end"])
                )
                first += ahead + spec["steps"]
        result["sent"] = sorted({fields[0] for fields in gateway.received})
        return result
    finally:
        client.close()
        await gateway.close()


async def replay_all(names: list[str]) -> dict[str, dict[str, Any]]:
    done = await asyncio.gather(*(asyncio.wait_for(replay(n), HUNG) for n in names), return_exceptions=True)
    return {
        name: {"crashed": repr(result)} if isinstance(result, BaseException) else result
        for name, result in zip(names, done, strict=True)
    }


@pytest.fixture(scope="module")
def replayed() -> dict[str, dict[str, Any]]:
    return asyncio.run(replay_all(conversation_names()))


@pytest.mark.parametrize("name", conversation_names())
def test_the_python_client_answers_what_the_typescript_did(name: str, replayed: dict[str, dict[str, Any]]) -> None:
    got = replayed[name]
    assert "crashed" not in got, f"{name}: the replay itself failed: {got['crashed']}"
    expected = load_expectation(name)
    assert got["ask"] == expected["ask"], f"{name}: the expectation was made for another ask"
    assert same(got["expect"], expected["expect"]), (
        f"{name}: the Python client said\n  {got['expect']!r}\nwhere the TypeScript's said\n  {expected['expect']!r}"
    )
    assert ("later" in got) == ("later" in expected), f"{name}: later asks on one side only"
    for i, (mine, theirs) in enumerate(zip(got.get("later", []), expected.get("later", []), strict=True)):
        assert mine["ask"] == theirs["ask"], f"{name}: later[{i}] was a different ask"
        assert same(mine["expect"], theirs["expect"]), (
            f"{name}: later[{i}]: the Python client said\n  {mine['expect']!r}\n"
            f"where the TypeScript's said\n  {theirs['expect']!r}"
        )
    assert ("accountReads" in got) == ("accountReads" in expected), f"{name}: account reads on one side only"
    for i, (mine, theirs) in enumerate(zip(got.get("accountReads", []), expected.get("accountReads", []), strict=True)):
        assert mine["wanted"] == theirs["wanted"], f"{name}: accountReads[{i}] asked for another account"
        assert same(mine["expect"], theirs["expect"]), (
            f"{name}: accountReads[{i}]: the Python client said\n  {mine['expect']!r}\n"
            f"where the TypeScript's said\n  {theirs['expect']!r}"
        )
        # the messages too: exactly a subscribe and its unsubscribe, or nothing for a refusal
        assert mine["sent"] == theirs["sent"], (
            f"{name}: accountReads[{i}]: the Python client sent {mine['sent']} where the TypeScript's sent {theirs['sent']}"
        )
    assert ("watches" in got) == ("watches" in expected), f"{name}: watches on one side only"
    for i, (mine, theirs) in enumerate(zip(got.get("watches", []), expected.get("watches", []), strict=True)):
        assert mine.keys() == theirs.keys(), f"{name}: watches[{i}] came to {sorted(mine)} where {sorted(theirs)}"
        for key in theirs:
            assert same(mine[key], theirs[key]), (
                f"{name}: watches[{i}].{key}: the Python client said\n  {mine[key]!r}\n"
                f"where the TypeScript's said\n  {theirs[key]!r}"
            )


@pytest.mark.parametrize("name", conversation_names())
def test_the_python_client_sends_only_what_the_typescript_does(name: str, replayed: dict[str, dict[str, Any]]) -> None:
    """The TypeScript's five messages and startApi, and an account subscription only to read one.

    `ib_async`'s `IB.connectAsync` asks for positions on every connect whatever its fetch flags
    say, and orders unless `readonly=True`. A quote fetch has nothing account-shaped in it, so this
    client connects through `ib_async`'s `Client` instead and sends what `messages.ts` sends:
    startApi (71), reqMarketDataType (59), reqContractDetails (9), reqMktData (1) and cancelMktData
    (2) — and reqAccountUpdates (6) where, and only where, a conversation reads the account (ADR
    0030), and the P&L requests and their cancels (92 to 95) only where it watches it (ADR 0031),
    held message for message by the comparison above."""
    got = replayed[name]
    assert "crashed" not in got, got.get("crashed")
    allowed = {"71", "59", "9", "1", "2"} | ({"6"} if "accountReads" in got else set())
    allowed |= WATCH_MESSAGES if "watches" in got else set()
    assert set(got["sent"]) <= allowed, f"{name}: the client also sent {got['sent']}"


def test_every_recording_has_its_expectation_and_its_python_result() -> None:
    recordings, expectations = set(conversation_names()), set(expectation_names())
    assert len(recordings) >= FLOOR, f"only {len(recordings)} recordings — the directory is not where it was"
    assert recordings - expectations == set(), (
        f"recorded but never expected: {sorted(recordings - expectations)} — run `make cases`"
    )
    assert expectations - recordings == set(), f"expected but never recorded: {sorted(expectations - recordings)}"
    # and the comparison is parametrized over exactly these — read off the test itself, so a list
    # written out by hand in its place, which would go stale, fails here
    (mark,) = test_the_python_client_answers_what_the_typescript_did.pytestmark  # type: ignore[attr-defined]
    assert set(mark.args[1]) == recordings, "the comparison does not replay every recording"
