/** `/health`, the one route that needs no token (ADR 0009, phase 5).
 *
 *  It is what the dashboard's Service panel reads: the database, the Provider and the sweep's
 *  state. The queue and the last run went with the run pipeline in phase 10 (ADR 0014). It carries no
 *  `contract_version` — that and the skew banner it fed went in ADR 0009 phase 8, when the frontend started taking its types FROM this API (`hc<AppType>`), so a
 *  response that has changed shape is a compile error in the frontend's workspace rather than a
 *  runtime notice. The two services still deploy separately (ADR 0006); `make deploy` restarting
 *  both is what addresses that.
 *
 *  Every branch reports rather than raises. A health endpoint that 500s when the database is gone
 *  tells you less than one that says `db: false`.
 */
import { Hono } from "hono";
import { z } from "zod";

import type { Deps } from "../deps.ts";
import type { QuoteGradeReading } from "../../../ports.ts";
import { databaseResponds } from "../../../db/queries/index.ts";
import { GOLDEN_CASES } from "optionality/golden";
import { documented } from "../openapi.ts";
import { displayTime } from "optionality/domain/timefmt";
import { sweepInterval } from "../../../sweep-interval.ts";
import { SweepSettings, sweepSettings } from "./settings.ts";

/** Whether the option prices are real-time (#464): the account's grade for US options, which moomoo
 *  states by LEVEL and never as a delay, so "not real-time" is all that can be said — by how many
 *  minutes, never. Every key in every state, so a reader need not tell absent from null. */
const QuoteGrade = z.object({
  /** moomoo's own grade, as the Python SDK names it: N/A, BMP, LV1, LV2, LV3, SF or NO; null when
   *  none has been read */
  us_option: z.string().nullable(),
  /** LV1, LV2, LV3 and SF are; BMP and NO are not; null for N/A (moomoo's Unknow) or unread */
  realtime: z.boolean().nullable(),
  /** when it was read, in the display zone; an earlier read's after one that failed */
  read_at: z.string().nullable(),
  /** null when a grade has been read; otherwise why there is none, in one sentence */
  reason: z.string().nullable(),
});

/** The words for why there is no grade. Kept here, with the route, because they are `/health`'s:
 *  the Provider says only what it read and what went wrong. */
const NOT_READ = "not read yet since the service started";
const REPORTS_NONE = "this Provider reports no account grade";

/** A Provider's reading, as `/health` serves it. A read that failed leaves an earlier grade in
 *  place, and that grade is served as read — its `read_at` says how old it is (#464). */
function servedGrade(reading: QuoteGradeReading | null, tz: string): z.infer<typeof QuoteGrade> {
  if (reading?.read) {
    const { usOption, realtime, at } = reading.read;
    return { us_option: usOption, realtime, read_at: displayTime(at, tz), reason: null };
  }
  const reason = reading === null ? REPORTS_NONE
    : reading.failure !== null ? `the read failed: ${reading.failure}`
    : NOT_READ;
  return { us_option: null, realtime: null, read_at: null, reason };
}

const HealthResponse = z.object({
  db: z.boolean(),
  /** Which Provider this deployment reads, and whether it is answering. It was `opend: boolean`
   *  until #169 — the vendor's name on the API contract, which the dashboard then printed
   *  whatever was actually behind the port (ADR 0015). And, since #464, whether the option prices
   *  it serves are real-time: nothing else the service serves says so, because a moomoo quote
   *  carries no flag. */
  provider: z.object({ name: z.string(), ok: z.boolean(), quote_grade: QuoteGrade }),
  /** Which golden cases this service IS (ADR 0016) — the fingerprint of testdata/golden/*.json,
   *  generated by `make cases`. Not for the dashboard, which takes its types from this API and so
   *  cannot be stale: it is for `python/`, whose port is held to the TypeScript only at the moment
   *  it is written. A notebook pins a tag for months; this is the one thing that tells it the
   *  engine has moved since. */
  golden_cases: z.string(),
  monitor: z.object({
    last_sweep_at: z.string().nullable(),
    last_sweep_ok: z.boolean(),
    consecutive_failures: z.number(),
    alarms: z.object({ label: z.string(), bad: z.boolean() }),
    fetched_at: z.string().nullable(),
  }),
  settings: z.object({
    /** the horizon the dashboard weighs a fill against when it is reading pressure rather than
     *  distance — one definition, because a second copy of 21 in the frontend drifts the first
     *  time EXIT_MANAGE_BY_DTE moves */
    manage_by_dte: z.number(),
    expired_retention_days: z.number(),
    display_tz: z.string(),
    /** the sweep's interval IN FORCE — the page's choice or `.env`'s — where it came from, the
     *  default, and the presets (#442): what `PATCH /settings` answers too */
  }).extend(SweepSettings.shape),
});

const health = documented("Service health; needs no token", { 200: HealthResponse });

export function healthRoutes(deps: Deps) {
  return new Hono().get("/health", health, async (c) => {
    const { settings, db, sweeper } = deps;
    const tz = settings.displayTz;
    const ok = databaseResponds(db);

    return health.reply(c, 200, {
        db: ok,
        golden_cases: GOLDEN_CASES,
        // What the last batch did, falling back to the Provider's own probe only while nothing
        // has been asked for yet. The probe alone was a green light for a gateway this service
        // could not speak to: on 2026-10-16 OpenD held the WEBSOCKET port open and timed out every
        // login, so this read true while every market-data route returned 502. An answered request
        // is the only evidence that matters, and reusing the sweep's costs no extra call (ADR 0010).
        provider: {
          name: deps.provider.name,
          ok: sweeper.lastFetchOk() ?? await deps.provider.reachable(),
          // what the Provider last read, never a read of its own: it is read once per connection
          // episode, after a fetch that worked (#464)
          quote_grade: servedGrade(deps.provider.quoteGrade(), tz),
        },
        monitor: {
          last_sweep_at: displayTime(sweeper.lastSweepAt(), tz),
          last_sweep_ok: sweeper.lastSweepOk(),
          consecutive_failures: sweeper.consecutiveFailures(),
          alarms: sweeper.alarmState(),
          fetched_at: displayTime(sweeper.lastFetchAt(), tz),
        },
        // knobs a client cannot guess: the sweep cadence the meta line names — read from the
        // database, so a choice made on the page shows at once (#442) — and the retention window
        // the muted table counts down to
        settings: {
          manage_by_dte: settings.exitManageByDte,
          expired_retention_days: settings.expiredRetentionDays,
          display_tz: settings.displayTz,
          ...sweepSettings(sweepInterval(db, settings)),
        },
      });
  });
}
