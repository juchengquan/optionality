/** The fingerprint of what the port must reproduce (ADR 0016).
 *
 *  `python/`'s version says WHEN it was cut; this says WHAT it agrees with. A date cannot answer
 *  the only question a notebook has — "is this port from before or after the rounding fix" — and a
 *  commit sha answers it too eagerly: a frontend timestamp trim changes the sha and cannot possibly
 *  affect the port, so a sha-based stamp cries wolf until it is ignored.
 *
 *  `testdata/golden/*.json` IS the contract. `make cases` regenerates it whenever anything
 *  `backend/src/domain/` exports changes, so a hash of those files moves exactly when the thing the
 *  port must reproduce moves, and never otherwise. Its README is prose and is left out: a comment
 *  edit must not look like a domain change.
 *
 *  Twelve hex characters. It is read by eye in a notebook header and compared by machine against
 *  `/health`; 48 bits is far past collision for nine files that one command writes.
 */
import { createHash } from "node:crypto";

export const STAMP_LENGTH = 12;

/** The rendered case files, by name without `.json` — the generator's own output, so the hash is
 *  of what SHOULD be on disk rather than what is. A stale checkout cannot talk itself into
 *  agreement. */
export function goldenHash(rendered: Record<string, string>): string {
  const sum = createHash("sha256");
  // sorted, and the name goes in with the text: two files whose contents swapped would otherwise
  // hash the same, and the set of case modules is part of the contract
  for (const name of Object.keys(rendered).sort()) {
    sum.update(`${name}\n${rendered[name]!}`);
  }
  return sum.digest("hex").slice(0, STAMP_LENGTH);
}

/** Both stamps are GENERATED AND COMMITTED, not computed at build time. A build hook reaching
 *  `../../testdata/golden/` works from a git clone and silently produces nothing from an sdist,
 *  which cannot carry a directory outside `python/` — measured 2026-11-01. A stamp that is
 *  sometimes absent is worse than none, because it stops being read. Committed, it ships in every
 *  wheel from every build path, and `make check-cases` proves it is current. */
export const tsStamp = (hash: string): string =>
  `/** Generated by \`make cases\` (ADR 0016) — do not edit. The fingerprint of
 *  testdata/golden/*.json, which \`/health\` carries so a notebook can ask whether its port still
 *  agrees with the engine that is running (optionality.api.agrees). */
export const GOLDEN_CASES = "${hash}";
`;

export const pythonStamp = (hash: string): string =>
  `"""Generated by \`make cases\` (ADR 0016) — do not edit.

The golden cases this port was written against: the fingerprint of testdata/golden/*.json. The
package version says when it was cut; this says what it agrees with. \`optionality.api.agrees\`
compares it with the running service's own.
"""

GOLDEN_CASES = "${hash}"
`;
